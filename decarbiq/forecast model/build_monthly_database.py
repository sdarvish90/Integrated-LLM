def build_monthly_database():
    """Build comprehensive monthly CSV database."""
    
    rows = []
    
    for year in range(1997, 2026):
        for month in range(1, 13):
            # Skip future months
            if year == 2025 and month > 11:
                continue
            if year == 2026:
                continue
                
            row = {
                'year': year,
                'month': month,
                'period': f"{year}-{month:02d}",
            }
            
            # Henry Hub
            if year in HENRY_HUB_MONTHLY:
                hh = HENRY_HUB_MONTHLY[year]
                if month <= len(hh) and hh[month-1] is not None:
                    row['henry_hub_spot'] = hh[month-1]
                else:
                    row['henry_hub_spot'] = ''
            else:
                row['henry_hub_spot'] = ''
            
            # Texas Citygate
            if year in TEXAS_CITYGATE_MONTHLY:
                tx = TEXAS_CITYGATE_MONTHLY[year]
                if month <= len(tx) and tx[month-1] is not None:
                    row['texas_citygate'] = tx[month-1]
                else:
                    row['texas_citygate'] = ''
            else:
                row['texas_citygate'] = ''
            
            # California Citygate
            if year in CALIFORNIA_CITYGATE_MONTHLY:
                ca = CALIFORNIA_CITYGATE_MONTHLY[year]
                if month <= len(ca) and ca[month-1] is not None:
                    row['california_citygate'] = ca[month-1]
                else:
                    row['california_citygate'] = ''
            else:
                row['california_citygate'] = ''
            
            # Calculate basis differentials
            if row['henry_hub_spot'] and row['texas_citygate']:
                row['texas_basis'] = round(float(row['texas_citygate']) - float(row['henry_hub_spot']), 2)
            else:
                row['texas_basis'] = ''
            
            if row['henry_hub_spot'] and row['california_citygate']:
                row['california_basis'] = round(float(row['california_citygate']) - float(row['henry_hub_spot']), 2)
            else:
                row['california_basis'] = ''
            
            rows.append(row)
    
    return rows


def save_to_csv(rows, filename):
    """Save rows to CSV file."""
    if not rows:
        return
    
    fieldnames = ['year', 'month', 'period', 'henry_hub_spot', 'texas_citygate', 
                  'california_citygate', 'texas_basis', 'california_basis']
    
    with open(filename, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    
    print(f"Saved {len(rows)} records to {filename}")


def print_summary_stats(rows):
    """Print summary statistics."""
    
    print("\n" + "="*60)
    print("MONTHLY DATABASE SUMMARY STATISTICS")
    print("="*60)
    
    # Filter to rows with all data
    complete_rows = [r for r in rows if r['henry_hub_spot'] and r['texas_citygate'] and r['california_citygate']]
    
    print(f"\nTotal records: {len(rows)}")
    print(f"Complete records (all prices): {len(complete_rows)}")
    
    # Year range
    years = [r['year'] for r in rows]
    print(f"Date range: {min(years)} to {max(years)}")
    
    # Price ranges
    hh_prices = [float(r['henry_hub_spot']) for r in complete_rows]
    tx_prices = [float(r['texas_citygate']) for r in complete_rows]
    ca_prices = [float(r['california_citygate']) for r in complete_rows]
    
